#!/usr/bin/env node
// UI parity audit: every TOOL_ACTION KiCad defines (src/kicad/actions.json,
// extracted from the pinned KiCad source) vs. whether this studio wires it.
// An action counts as wired when its name appears as a handler key
// (`m.set("<name>", ...)`, or `registry.set(...)` in the schematic clipboard module) or any string literal in non-test UI source.
// An action that is deliberately not wired is listed with its reason in
// tools/ui-parity-missing.json ({ "<name>": "<why>" }) and shows up as
// `missing: <why>` instead of a bare `missing` -- no fake handler stands in
// for a subsystem this studio does not have.
// Writes docs/parity/UI-ACTIONS.md.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const actions = JSON.parse(readFileSync(join(root, "src/kicad/actions.json"), "utf8")).actions;
const reasonsPath = join(root, "tools/ui-parity-missing.json");
const reasons = existsSync(reasonsPath) ? JSON.parse(readFileSync(reasonsPath, "utf8")) : {};

function walk(d, out = []) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|tsx)$/.test(f) && !/\.test\./.test(f) && !p.includes("/kicad/")) out.push(p);
  }
  return out;
}
const src = walk(join(root, "src")).map((p) => readFileSync(p, "utf8")).join("\n");
const handled = new Set([...src.matchAll(/\b(?:m|registry)\.set\(\s*"([^"]+)"/g)].map((m) => m[1]));
const mentioned = new Set([...src.matchAll(/"((?:pcbnew|eeschema|common)\.[A-Za-z0-9_.]+)"/g)].map((m) => m[1]));

// A reason for an action that is wired, or for one KiCad does not define, is stale: say so.
const known = new Set(actions.map((a) => a.name));
for (const name of Object.keys(reasons)) {
  if (!known.has(name)) console.warn(`ui-parity-missing.json: "${name}" is not a KiCad action`);
  else if (handled.has(name)) console.warn(`ui-parity-missing.json: "${name}" is wired now -- drop its reason`);
}

const editor = (n) => (n.startsWith("pcbnew.") ? "pcbnew" : n.startsWith("eeschema.") ? "eeschema" : "common");
const rows = actions.map((a) => {
  const isHandled = handled.has(a.name);
  const reason = !isHandled && reasons[a.name] ? String(reasons[a.name]) : null;
  const state = isHandled ? "handled" : reason ? `missing: ${reason}` : mentioned.has(a.name) ? "referenced" : "missing";
  return { ...a, editor: editor(a.name), state, declined: reason != null };
});

const groups = ["pcbnew", "eeschema", "common"];
let md = `# UI parity: KiCad actions vs this studio\n\nGenerated by \`web/studio/tools/ui-parity-audit.mjs\` from \`src/kicad/actions.json\` (KiCad ${actions.length} actions).\n\n- **handled**: registered as an action handler (\`useActionRunner\`)\n- **referenced**: named in UI code (menus, toolbars, tab gating) but no handler\n- **missing**: not wired at all\n- **missing: <reason>**: deliberately not wired -- the reason is recorded in \`tools/ui-parity-missing.json\` (a subsystem this studio does not have; no fake handler stands in for it)\n\n| editor | actions | handled | referenced | missing | missing with a reason | hotkeyed & not handled |\n|---|---|---|---|---|---|---|\n`;
for (const g of groups) {
  const r = rows.filter((x) => x.editor === g);
  const c = (s) => r.filter((x) => x.state === s).length;
  md += `| ${g} | ${r.length} | ${c("handled")} | ${c("referenced")} | ${c("missing")} | ${r.filter((x) => x.declined).length} | ${r.filter((x) => x.state !== "handled" && x.hotkey).length} |\n`;
}
for (const g of groups) {
  md += `\n## ${g}: not handled, hotkeyed first\n\n| action | label | hotkey | state |\n|---|---|---|---|\n`;
  const r = rows.filter((x) => x.editor === g && x.state !== "handled").sort((a, b) => (b.hotkey ? 1 : 0) - (a.hotkey ? 1 : 0) || a.name.localeCompare(b.name));
  for (const x of r) md += `| \`${x.name}\` | ${(x.label || "").replace(/\|/g, "\\|")} | ${x.hotkey ?? ""} | ${x.state.replace(/\|/g, "\\|")} |\n`;
}
writeFileSync(join(root, "../../docs/parity/UI-ACTIONS.md"), md);
console.log(md.split("\n").slice(0, 16).join("\n"));
