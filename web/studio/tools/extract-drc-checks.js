#!/usr/bin/env node
// Extracts the DRC checks Board Setup > Violation Severity lists -- the settings key, the title, the
// heading each belongs under and the severity `BOARD_DESIGN_SETTINGS` gives it when nothing is set --
// from KiCad's own source:
//
//   KICAD_SRC_DIR=~/ws/kicad-src-8303b2ad node tools/extract-drc-checks.js
//
// Reads pcbnew/drc/drc_item.cpp (`DRC_ITEM::allItemTypes`, the ordered list of headings and items that
// `GetItemsWithSeverities()` returns, up to `heading_internal`) and pcbnew/board_design_settings.cpp
// (the constructor's `m_DRCSeverities[...]` defaults), and writes two files that must agree:
//
//   src/kicad/drc_checks.json            -- what the severities page renders
//   ../../crates/model/src/drc_checks.rs -- the keys the model accepts (eda_model::rules::DRC_CHECKS)
//
// `--check` prints nothing and exits 1 if either file would change (for the unit test).

import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { readKicadFile, resolveCommit } from "./lib/kicadSource.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_JSON = join(__dirname, "..", "src", "kicad", "drc_checks.json");
const OUT_RS = join(__dirname, "..", "..", "..", "crates", "model", "src", "drc_checks.rs");

const ITEM_FILE = "pcbnew/drc/drc_item.cpp";
const SETTINGS_FILE = "pcbnew/board_design_settings.cpp";

/** `DRC_ITEM DRC_ITEM::name( DRCE_CODE, _HKI( "Title" ), wxT( "key" ) );` -> name -> {code, title, key}. */
export function parseItems(text) {
  const items = new Map();
  const re = /DRC_ITEM\s+DRC_ITEM::(\w+)\(\s*(\w+)\s*,\s*_HKI\(\s*"((?:[^"\\]|\\.)*)"\s*\)\s*,\s*(?:wxT\(\s*)?"((?:[^"\\]|\\.)*)"\s*\)?\s*\)\s*;/g;
  let m;
  while ((m = re.exec(text))) items.set(m[1], { code: m[2], title: m[3].replace(/\\"/g, '"'), key: m[4] });
  return items;
}

/** The names inside `DRC_ITEM::allItemTypes( { ... } )`, in order. */
export function parseOrder(text) {
  const start = text.indexOf("DRC_ITEM::allItemTypes(");
  if (start < 0) throw new Error("allItemTypes not found");
  const body = text.slice(start, text.indexOf("} );", start));
  return [...body.matchAll(/DRC_ITEM::(\w+)\s*,/g)].map((m) => m[1]);
}

/** `m_DRCSeverities[ DRCE_X ] = RPT_SEVERITY_WARNING;` -> code -> "warning" ("error" for every code the constructor loops over). */
export function parseSeverities(text) {
  const out = new Map();
  for (const m of text.matchAll(/m_DRCSeverities\[\s*(DRCE_\w+)\s*\]\s*=\s*RPT_SEVERITY_(ERROR|WARNING|IGNORE)\s*;/g)) out.set(m[1], m[2].toLowerCase());
  return out;
}

export function build(itemText, settingsText) {
  const items = parseItems(itemText);
  const severities = parseSeverities(settingsText);
  const groups = [];
  for (const name of parseOrder(itemText)) {
    if (name === "heading_internal") break; // "DRC_ITEM types with no user-editable severities"
    const it = items.get(name);
    if (!it) continue;
    if (name.startsWith("heading_")) {
      groups.push({ title: it.title, items: [] });
      continue;
    }
    if (!it.key || !it.title || !groups.length) continue;
    groups[groups.length - 1].items.push({ key: it.key, title: it.title, code: it.code, defaultSeverity: severities.get(it.code) ?? "error" });
  }
  return groups.filter((g) => g.items.length);
}

export function rustFile(groups, commit) {
  const rows = groups.flatMap((g) => g.items.map((i) => `    ("${i.key}", "${i.defaultSeverity}"),`));
  return `// GENERATED by web/studio/tools/extract-drc-checks.js from KiCad ${commit.sha} (pcbnew/drc/drc_item.cpp and
// pcbnew/board_design_settings.cpp). Do not edit by hand: run the extractor again.

/// \`DRC_ITEM::GetItemsWithSeverities()\`: the DRC settings keys Board Setup > Violation Severity lists, in KiCad's
/// order, with the severity \`BOARD_DESIGN_SETTINGS\` gives each when nothing is set.
pub const DRC_CHECKS: &[(&str, &str)] = &[
${rows.join("\n")}
];
`;
}

function main() {
  const commit = resolveCommit();
  const groups = build(readKicadFile(ITEM_FILE), readKicadFile(SETTINGS_FILE));
  const json = JSON.stringify({ commit: commit.sha, source: [ITEM_FILE, SETTINGS_FILE], groups }, null, 2) + "\n";
  const rs = rustFile(groups, commit);
  if (process.argv.includes("--check")) {
    const same = (path, text) => {
      try {
        return readFileSync(path, "utf8") === text;
      } catch {
        return false;
      }
    };
    process.exit(same(OUT_JSON, json) && same(OUT_RS, rs) ? 0 : 1);
  }
  writeFileSync(OUT_JSON, json);
  writeFileSync(OUT_RS, rs);
  console.log(`${groups.reduce((n, g) => n + g.items.length, 0)} checks in ${groups.length} groups -> ${OUT_JSON}, ${OUT_RS}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
