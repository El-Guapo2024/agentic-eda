// Tests for tools/extract-rules-help.js and tools/extract-rule-completions.js: how they read KiCad's C++ (the help texts an `OnSyntaxHelp`
// includes, a markdown2C header, the PROPERTY registrations and their SetIsHiddenFromRulesEditor, RegisterAllFunctions) and, when
// KICAD_SRC_DIR points at KiCad's source, that src/kicad/rules_help.json and src/kicad/rule_completions.json are what they make of it (`--check`).
// Plain Node: node --test tools/lib/rulesEditorExtract.test.js
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build as buildHelp, decodeHelpHeader, functionBody, includedHelp } from "../extract-rules-help.js";
import { scanFunctions, scanProperties, stripComments } from "../extract-rule-completions.js";

const here = dirname(fileURLToPath(import.meta.url));

const PANEL = `
void PANEL_SETUP_RULES::OnCompile( wxCommandEvent& event ) { if( x ) { y(); } }

void PANEL_SETUP_RULES::OnSyntaxHelp( wxHyperlinkEvent& aEvent )
{
    if( m_helpWindow )
    {
        m_helpWindow->ShowModeless();
        return;
    }
    wxString t =
#include "dialogs/panel_setup_rules_help_1clauses.h"
            ;
    t =
#include <panel_setup_condition_help_1clauses.h>
            ;
}
`;

test("the help texts a window shows: the #includes in its function, in order", () => {
  const body = functionBody(PANEL, "PANEL_SETUP_RULES::OnSyntaxHelp");
  assert.ok(body.startsWith("{") && body.endsWith("}") && !body.includes("OnCompile"));
  assert.deepEqual(includedHelp(body), ["pcbnew/dialogs/panel_setup_rules_help_1clauses.h", "pcbnew/dialogs/panel_setup_condition_help_1clauses.h"]);
  assert.throws(() => functionBody(PANEL, "PANEL_SETUP_RULES::Nope"));
});

test("a markdown2C header decodes to its markdown; a header that disagrees with its .md stops the extractor", () => {
  const md = '### Title\n\n    (condition "<expression>")\n\\\\ back\n';
  // markdown2C.cmake: `\` -> `\\`, `"` -> `\"`, each line end -> `\n"` + newline + `"`
  const h = `// Do not edit this file, it is autogenerated by CMake from the .md file\n_HKI( "${md.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, '\\n"\n"')}" );\n`;
  assert.equal(decodeHelpHeader(h), md);
  const files = {
    "pcbnew/dialogs/panel_setup_rules.cpp": PANEL.replace("PANEL_SETUP_RULES::OnSyntaxHelp", "PANEL_SETUP_RULES::OnSyntaxHelp"),
    "pcbnew/drc/rule_editor/panel_drc_rule_editor.cpp": PANEL.replace("PANEL_SETUP_RULES::OnSyntaxHelp", "PANEL_DRC_RULE_EDITOR::onSyntaxHelp"),
    "pcbnew/dialogs/panel_setup_rules_help_1clauses.h": h,
    "pcbnew/dialogs/panel_setup_rules_help_1clauses.md": md,
    "pcbnew/dialogs/panel_setup_condition_help_1clauses.h": h,
    "pcbnew/dialogs/panel_setup_condition_help_1clauses.md": md,
  };
  const out = buildHelp((f) => files[f]);
  assert.deepEqual(out.setupRules, ["pcbnew/dialogs/panel_setup_rules_help_1clauses.h", "pcbnew/dialogs/panel_setup_condition_help_1clauses.h"]);
  assert.equal(out.texts["pcbnew/dialogs/panel_setup_rules_help_1clauses.h"], md);
  files["pcbnew/dialogs/panel_setup_rules_help_1clauses.md"] = md + "changed\n";
  assert.throws(() => buildHelp((f) => files[f]), /is not what markdown2C.cmake makes/);
});

const DESC = `
static struct BOARD_CONNECTED_ITEM_DESC
{
    BOARD_CONNECTED_ITEM_DESC()
    {
        PROPERTY_MANAGER& propMgr = PROPERTY_MANAGER::Instance();
        // propMgr.AddProperty( new PROPERTY<X, int>( _HKI( "Commented Out" ), &X::Set, &X::Get ) );
        auto layer = new PROPERTY_ENUM<BOARD_CONNECTED_ITEM, PCB_LAYER_ID>(
                _HKI( "Layer" ), &BOARD_CONNECTED_ITEM::SetLayer, &BOARD_CONNECTED_ITEM::GetLayer );
        layer->SetChoices( layerEnum.Choices() );
        propMgr.ReplaceProperty( TYPE_HASH( BOARD_ITEM ), _HKI( "Layer" ), layer );

        propMgr.AddProperty( new PROPERTY_ENUM<BOARD_CONNECTED_ITEM, int>( _HKI( "Net" ),
                             &BOARD_CONNECTED_ITEM::SetNetCode, &BOARD_CONNECTED_ITEM::GetNetCode, PT_NET ) )
                .SetIsHiddenFromRulesEditor()
                .SetIsHiddenFromLibraryEditors();
        propMgr.AddProperty( new PROPERTY<BOARD_CONNECTED_ITEM, wxString>( _HKI( "NetClass" ),
                             NO_SETTER( BOARD_CONNECTED_ITEM, wxString ), &BOARD_CONNECTED_ITEM::GetNetClassName ) )
                .SetIsHiddenFromPropertiesManager();
        propMgr.AddProperty( new PROPERTY<EDA_ITEM, std::optional<int>, Base>( wxS( "Type" ), NO_SETTER( EDA_ITEM, KICAD_T ), &EDA_ITEM::Type ) )
                .SetIsHiddenFromRulesEditor( false );
        auto hiddenVar = new PROPERTY<X, bool>( _HKI( "Hidden Var" ), &X::Set, &X::Get );
        hiddenVar->SetIsHiddenFromRulesEditor();
        propMgr.AddProperty( hiddenVar, group );
        auto unused = new PROPERTY<X, bool>( _HKI( "Never Added" ), &X::Set, &X::Get );
        const wxString url = wxS( "http://example.com" ); // a // inside a string is not a comment
    }
} _BOARD_CONNECTED_ITEM_DESC;
`;

test("the property registrations: the name, hidden or not, a variable only when it is added, comments skipped", () => {
  assert.ok(!stripComments(DESC).includes("Commented Out"));
  assert.ok(stripComments(DESC).includes('wxS( "http://example.com" )'));
  assert.deepEqual(
    scanProperties(DESC, "x.cpp").map((p) => [p.name, p.hidden]),
    [
      ["Layer", false],
      ["Net", true],
      ["NetClass", false],
      ["Type", false],
      ["Hidden Var", true],
    ]
  );
});

test("RegisterAllFunctions: the signatures in order, DEPRECATED kept", () => {
  const src = `void PCBEXPR_BUILTIN_FUNCTIONS::RegisterAllFunctions()
{
    m_funcs.clear();
    RegisterFunc( wxT( "existsOnLayer('x')" ), existsOnLayerFunc );
    // RegisterFunc( wxT( "commented()" ), x );
    RegisterFunc( wxT( "insideCourtyard('x') DEPRECATED" ), intersectsCourtyardFunc, true );
}
void Other() { RegisterFunc( wxT( "elsewhere()" ), f ); }`;
  assert.deepEqual(scanFunctions(src), ["existsOnLayer('x')", "insideCourtyard('x') DEPRECATED"]);
});

test("src/kicad/rules_help.json and src/kicad/rule_completions.json are what the extractors make of KiCad's source (KICAD_SRC_DIR)", () => {
  if (!process.env.KICAD_SRC_DIR) {
    console.log("skipped: set KICAD_SRC_DIR to KiCad's source to check the generated files against it");
    return;
  }
  for (const tool of ["extract-rules-help.js", "extract-rule-completions.js"]) execFileSync(process.execPath, [join(here, "..", tool), "--check"], { env: process.env, stdio: "inherit" });
});
