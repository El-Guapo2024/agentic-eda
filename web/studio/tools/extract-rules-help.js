#!/usr/bin/env node
// Extracts the Syntax Help of the custom rules editors -- the markdown texts KiCad compiles into pcbnew and shows, through
// `ConvertMarkdown2Html` and an `HTML_MESSAGE_BOX` titled "Syntax Help", from the "Syntax help" link -- word for word from KiCad's source:
//
//   KICAD_SRC_DIR=~/src/kicad-src-8303b2ad node tools/extract-rules-help.js
//
// Reads which texts each window shows, in order, from the `#include`s in the body of
//   pcbnew/dialogs/panel_setup_rules.cpp            PANEL_SETUP_RULES::OnSyntaxHelp      (Board Setup > Design Rules > Custom Rules)
//   pcbnew/drc/rule_editor/panel_drc_rule_editor.cpp PANEL_DRC_RULE_EDITOR::onSyntaxHelp (the DRC Rule Editor's condition)
// and each text from its pcbnew/dialogs/panel_setup_*_help_*.h -- the C string `_HKI( "..." )` that is what gets compiled in (pcbnew/CMakeLists.txt
// makes it from the .md next to it with cmake/BuildSteps/markdown2C.cmake, which only escapes `\` and `"` and splits the lines). The decoded
// string must be the .md exactly; the extractor stops when a header and its markdown disagree.
//
// Writes src/kicad/rules_help.json: { commit, source, texts: { "<file.h>": text }, setupRules: [file.h ...], ruleEditor: [file.h ...] }.
// `--check` prints nothing and exits 1 if the file would change (for the unit test).

import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { readKicadFile, resolveCommit } from "./lib/kicadSource.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "src", "kicad", "rules_help.json");

const WINDOWS = [
  { key: "setupRules", file: "pcbnew/dialogs/panel_setup_rules.cpp", fn: "PANEL_SETUP_RULES::OnSyntaxHelp" },
  { key: "ruleEditor", file: "pcbnew/drc/rule_editor/panel_drc_rule_editor.cpp", fn: "PANEL_DRC_RULE_EDITOR::onSyntaxHelp" },
];

/** The body of `void <fn>( ... ) { ... }`: from its opening brace to the brace that closes it. */
export function functionBody(text, fn) {
  const at = text.search(new RegExp(`\\b${fn.replace(/:/g, "\\:")}\\s*\\(`));
  if (at < 0) throw new Error(`${fn} not found`);
  const open = text.indexOf("{", at);
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "{") depth++;
    else if (text[i] === "}" && --depth === 0) return text.slice(open, i + 1);
  }
  throw new Error(`${fn}: no closing brace`);
}

/** The headers a body `#include`s, in order, as paths under pcbnew/dialogs/ (`"dialogs/x.h"` and `<x.h>` alike). */
export function includedHelp(body) {
  return [...body.matchAll(/#include\s*[<"]([^>"]+)[>"]/g)].map((m) => `pcbnew/dialogs/${m[1].replace(/^dialogs\//, "")}`);
}

/** The string a markdown2C header holds: its C string literals after `_HKI(`, concatenated and unescaped. */
export function decodeHelpHeader(text) {
  const start = text.indexOf("_HKI(");
  if (start < 0) throw new Error("no _HKI( in the header");
  const body = text.slice(start + 5, text.lastIndexOf(")"));
  let out = "";
  for (const m of body.matchAll(/"((?:[^"\\]|\\.)*)"/g)) {
    out += m[1].replace(/\\(.)/g, (_, c) => (c === "n" ? "\n" : c === "t" ? "\t" : c === "r" ? "\r" : c));
  }
  return out;
}

export function build(read) {
  const texts = {};
  const source = [];
  const out = {};
  for (const w of WINDOWS) {
    source.push(w.file);
    const files = includedHelp(functionBody(read(w.file), w.fn));
    if (!files.length) throw new Error(`${w.fn} includes no help text`);
    for (const h of files) {
      if (texts[h] !== undefined) continue;
      const text = decodeHelpHeader(read(h));
      const mdFile = h.replace(/\.h$/, ".md");
      if (text !== read(mdFile)) throw new Error(`${h} is not what markdown2C.cmake makes of ${mdFile}: regenerate it`);
      texts[h] = text;
      source.push(h, mdFile);
    }
    out[w.key] = files;
  }
  return { source, texts, ...out };
}

function main() {
  const commit = resolveCommit();
  const data = build(readKicadFile);
  const json =
    JSON.stringify(
      {
        commit: commit.sha,
        note: "GENERATED by web/studio/tools/extract-rules-help.js: the Syntax Help texts, in the order each window shows them (setupRules: PANEL_SETUP_RULES::OnSyntaxHelp; ruleEditor: PANEL_DRC_RULE_EDITOR::onSyntaxHelp). Do not edit by hand.",
        ...data,
      },
      null,
      2
    ) + "\n";
  if (process.argv.includes("--check")) {
    let same = false;
    try {
      same = readFileSync(OUT, "utf8") === json;
    } catch {
      same = false;
    }
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, json);
  console.log(`${Object.keys(data.texts).length} texts (${data.setupRules.length} for Custom Rules, ${data.ruleEditor.length} for the DRC Rule Editor) -> ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
