#!/usr/bin/env node
// Extracts the ERC checks Schematic Setup > Violation Severity lists -- the settings key, the title, the
// heading each belongs under and the severity `ERC_SETTINGS` gives it when nothing is set -- from KiCad's
// own source:
//
//   KICAD_SRC_DIR=~/ws/kicad-src-8303b2ad node tools/extract-erc-checks.js
//
// Reads eeschema/erc/erc_item.cpp (`ERC_ITEM::allItemTypes`, the ordered list of headings and items that
// `GetItemsWithSeverities()` returns, up to `heading_internal`) and eeschema/erc/erc_settings.cpp (the
// constructor's `m_ERCSeverities[...]` defaults), and writes two files that must agree:
//
//   src/kicad/erc_checks.json            -- what the severities page renders
//   ../../crates/model/src/erc_checks.rs -- the keys the model accepts (eda_model::erc_checks::ERC_CHECKS)
//
// The one row that is not an ordinary Error / Warning / Ignore choice is "Conflict problem between pins"
// (`pin_to_pin`, `ERC_ITEM::pinTableWarning`): `PANEL_SETUP_SEVERITIES` takes it out of its group and shows
// it last, as "From Pin Conflicts Map" or "Ignore" -- the pin map itself says warning or error. It is
// `pinMap` in the JSON, not one of the groups' items.
//
// `--check` prints nothing and exits 1 if either file would change (for the unit test).

import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { readKicadFile, resolveCommit } from "./lib/kicadSource.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_JSON = join(__dirname, "..", "src", "kicad", "erc_checks.json");
const OUT_RS = join(__dirname, "..", "..", "..", "crates", "model", "src", "erc_checks.rs");

const ITEM_FILE = "eeschema/erc/erc_item.cpp";
const SETTINGS_FILE = "eeschema/erc/erc_settings.cpp";

/** The `ERC_ITEM` the pin conflicts map owns: `PANEL_SETUP_SEVERITIES`'s `aPinMapSpecialCase` (dialog_schematic_setup.cpp passes `&ERC_ITEM::pinTableWarning`). */
const PIN_MAP_ITEM = "pinTableWarning";

const stripComments = (text) => text.replace(/\/\/[^\n]*/g, "");

/** `ERC_ITEM ERC_ITEM::name( ERCE_CODE, _HKI( "Title" ), wxT( "key" ) );` -> name -> {code, title, key}. */
export function parseItems(text) {
  const items = new Map();
  const re = /ERC_ITEM\s+ERC_ITEM::(\w+)\(\s*(\w+)\s*,\s*_HKI\(\s*"((?:[^"\\]|\\.)*)"\s*\)\s*,\s*(?:wxT\(\s*)?"((?:[^"\\]|\\.)*)"\s*\)?\s*\)\s*;/g;
  let m;
  while ((m = re.exec(stripComments(text)))) items.set(m[1], { code: m[2], title: m[3].replace(/\\"/g, '"'), key: m[4] });
  return items;
}

/** The names inside `ERC_ITEM::allItemTypes( { ... } )`, in order. */
export function parseOrder(text) {
  const clean = stripComments(text);
  const start = clean.indexOf("ERC_ITEM::allItemTypes(");
  if (start < 0) throw new Error("allItemTypes not found");
  const body = clean.slice(start, clean.indexOf("} );", start));
  return [...body.matchAll(/ERC_ITEM::(\w+)\s*,?/g)].map((m) => m[1]).filter((n) => n !== "allItemTypes");
}

/** `m_ERCSeverities[ERCE_X] = RPT_SEVERITY_WARNING;` -> code -> "warning" ("error" for every code the constructor loops over). */
export function parseSeverities(text) {
  const out = new Map();
  for (const m of stripComments(text).matchAll(/m_ERCSeverities\[\s*(ERCE_\w+)\s*\]\s*=\s*RPT_SEVERITY_(ERROR|WARNING|IGNORE)\s*;/g)) out.set(m[1], m[2].toLowerCase());
  return out;
}

export function build(itemText, settingsText) {
  const items = parseItems(itemText);
  const severities = parseSeverities(settingsText);
  const groups = [];
  let pinMap = null;
  for (const name of parseOrder(itemText)) {
    if (name === "heading_internal") break; // "ERC_ITEM types with no user-editable severities"
    const it = items.get(name);
    if (!it) continue;
    if (name.startsWith("heading_")) {
      groups.push({ title: it.title, items: [] });
      continue;
    }
    if (!it.key || !it.title || !groups.length) continue;
    const row = { key: it.key, title: it.title, code: it.code, defaultSeverity: severities.get(it.code) ?? "error" };
    if (name === PIN_MAP_ITEM) pinMap = row;
    else groups[groups.length - 1].items.push(row);
  }
  if (!pinMap) throw new Error("the pin conflicts map row is not in the list");
  return { groups: groups.filter((g) => g.items.length), pinMap };
}

export function rustFile({ groups, pinMap }, commit) {
  const rows = [...groups.flatMap((g) => g.items), pinMap].map((i) => `    ("${i.key}", "${i.defaultSeverity}"),`);
  return `// GENERATED by web/studio/tools/extract-erc-checks.js from KiCad ${commit.sha} (eeschema/erc/erc_item.cpp and
// eeschema/erc/erc_settings.cpp). Do not edit by hand: run the extractor again.

//! The ERC checks Schematic Setup > Violation Severity lists.

/// \`ERC_ITEM::GetItemsWithSeverities()\`: the ERC settings keys, in KiCad's order, with the severity \`ERC_SETTINGS\` gives each when
/// nothing is set. The last one, \`pin_to_pin\`, is the pin conflicts map's: Ignore or "from the map".
pub const ERC_CHECKS: &[(&str, &str)] = &[
${rows.join("\n")}
];

/// The severity \`ERC_SETTINGS\` gives \`key\` when nothing is set, or \`None\` for a key that is not an ERC check.
pub fn default_severity(key: &str) -> Option<&'static str> {
    ERC_CHECKS.iter().find(|(k, _)| *k == key).map(|(_, s)| *s)
}

/// Whether \`key\` is one of [\`ERC_CHECKS\`].
pub fn is_erc_check(key: &str) -> bool {
    default_severity(key).is_some()
}
`;
}

function main() {
  const commit = resolveCommit();
  const built = build(readKicadFile(ITEM_FILE), readKicadFile(SETTINGS_FILE));
  const json = JSON.stringify({ commit: commit.sha, source: [ITEM_FILE, SETTINGS_FILE], groups: built.groups, pinMap: built.pinMap }, null, 2) + "\n";
  const rs = rustFile(built, commit);
  if (process.argv.includes("--check")) {
    const same = (path, text) => {
      try {
        return readFileSync(path, "utf8") === text;
      } catch {
        return false;
      }
    };
    process.exit(same(OUT_JSON, json) && same(OUT_RS, rs) ? 0 : 1);
  }
  writeFileSync(OUT_JSON, json);
  writeFileSync(OUT_RS, rs);
  console.log(`${built.groups.reduce((n, g) => n + g.items.length, 0) + 1} checks in ${built.groups.length} groups -> ${OUT_JSON}, ${OUT_RS}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
