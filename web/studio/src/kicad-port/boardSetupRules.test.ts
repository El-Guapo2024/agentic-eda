// ---------------------------------------------------------------- patterns

test("a pattern is anchored: * is any run, ? any one character, everything else is itself", () => {
  assert.ok(globMatch("SPI_*", "SPI_MOSI"));
  assert.ok(globMatch("VBUS", "VBUS"));
  assert.ok(!globMatch("SPI_*", "I2C_SCL"));
  assert.ok(!globMatch("VBUS", "VBUS2"), "the whole name has to match");
  assert.ok(!globMatch("BUS", "VBUS"));
  assert.ok(globMatch("*", "anything"));
  assert.ok(globMatch("*", ""));
  assert.ok(globMatch("A*B*C", "AxxBxxC"));
  assert.ok(globMatch("A**C", "AC"));
  assert.ok(!globMatch("A*B*C", "AxxCxxB"));
  assert.ok(globMatch("D?", "D7") && !globMatch("D?", "D") && !globMatch("D?", "D77"));
  assert.ok(globMatch("+3.3V", "+3.3V") && !globMatch("+3.3V", "+3x3V"), "a dot is a dot, not any character");
  assert.ok(globMatch("Net-(R1-Pad1)", "Net-(R1-Pad1)"), "parentheses are the net's own characters");
  assert.ok(globMatch("A*", "A*B"), "a star in the name is matched by the pattern's star like any character");
  assert.ok(globMatch("*Pad1)", "Net-(R1-Pad1)"));
});

test("an alternation is a regular expression, which KiCad matches as it is: the nets it names are the nets of the pattern", () => {
  const nets = ["GND", "A", "B", "C", "SPI_MISO", "SPI_MOSI", "SPI_SCK", "D1_P", "D2_P", "D3_P", "A1", "Net-(R1-Pad1)", "Net-R1-Pad1", "AB", "ABCD"];
  assert.deepEqual(netsMatching("GND", nets), ["GND"]);
  assert.deepEqual(netsMatching("A|B|C", nets), ["A", "B", "C"]);
  assert.deepEqual(netsMatching("SPI_M(ISO|OSI)", nets), ["SPI_MISO", "SPI_MOSI"]);
  assert.deepEqual(netsMatching("D(1|2)_P", nets), ["D1_P", "D2_P"]);
  assert.deepEqual(netsMatching("A(|1)", nets), ["A", "A1"], "an empty alternative is the prefix itself");
  assert.deepEqual(netsMatching("A|", nets), ["A"], "the empty alternative matches only a net with no name");
  assert.deepEqual(netsMatching("Net-(R1-Pad1)", nets), ["Net-(R1-Pad1)", "Net-R1-Pad1"], "a regular expression (the group) and a wildcard pattern (the name itself): either will do");
  assert.deepEqual(netsMatching("(a|b)(c|d)", nets), [], "more than one group, no net named so");
  assert.deepEqual(netsMatching("(A|B)(C|D)?", nets), ["A", "B"], "a group with a quantifier");
  assert.deepEqual(netsMatching("", nets), []);
  assert.deepEqual(netsMatching("  GND ", nets), ["GND"], "the pattern is trimmed");
});

test("the pattern proposed for the nets picked is KiCad's: the name, or the common prefix with the tails", () => {
  assert.equal(proposePattern([]), "");
  assert.equal(proposePattern(["VBUS"]), "VBUS");
  assert.equal(proposePattern(["SPI_MOSI", "SPI_MISO"]), "SPI_M(ISO|OSI)");
  assert.equal(proposePattern(["D10", "D2", "D1"]), "D(1|2|10)", "the tails are in natural order");
  assert.equal(proposePattern(["GND", "VCC"]), "GND|VCC", "no common prefix: the names joined");
  assert.equal(proposePattern(["/A", "/B"]), "/A|/B", "a lone slash is not a prefix worth factoring");
  assert.equal(proposePattern(["a2", "A1"]), "A1|a2", "case is ignored when ordering, kept when writing");
  assert.equal(proposePattern(["VBUS", "VBUS"]), "VBUS", "the same net twice is one net");
});

test("what is proposed matches exactly the nets it was proposed for", () => {
  const sets = [["SPI_MOSI", "SPI_MISO", "SPI_SCK"], ["GND", "VCC"], ["D1", "D2", "D10"], ["A", "A1"], ["/rail/3V3", "/rail/5V"]];
  const universe = ["SPI_MOSI", "SPI_MISO", "SPI_SCK", "SPI_CS", "GND", "VCC", "D1", "D2", "D10", "D3", "A", "A1", "A2", "/rail/3V3", "/rail/5V", "/rail/12V", "SPI_M"];
  for (const set of sets) {
    const got = netsMatching(proposePattern(set), universe);
    assert.deepEqual([...got].sort(), [...set].sort(), proposePattern(set));
  }
});

test("assigning a pattern adds a row as typed, skips a copy, and keeps it under another class too (the nets are in both)", () => {
  let rows = addAssignment([], "SPI_M(ISO|OSI)", "bus");
  assert.deepEqual(rows, [{ pattern: "SPI_M(ISO|OSI)", netclass: "bus" }]);
  rows = addAssignment(rows, "SPI_M(ISO|OSI)", "bus");
  assert.equal(rows.length, 1, "an exact copy is not added");
  rows = addAssignment(rows, " SPI_M(ISO|OSI) ", "fast");
  assert.deepEqual(rows, [{ pattern: "SPI_M(ISO|OSI)", netclass: "bus" }, { pattern: "SPI_M(ISO|OSI)", netclass: "fast" }], "KiCad keeps both and composes the two classes for the nets it matches");
  assert.deepEqual(addAssignment(rows, "", "bus"), rows, "an empty pattern adds nothing");
});

test("Assign Netclass adds the pattern to the class chosen, or takes it off the others for Default", () => {
  const def = cls("Default", [], { clearance: 200 });
  const settings = { default: def, classes: [cls("power", ["VBUS"]), cls("bus", ["SPI_*"])] };
  const added = withAssignment(settings, "SPI_M(ISO|OSI)", "bus");
  assert.deepEqual(added.classes.map((c) => c.nets), [["VBUS"], ["SPI_*", "SPI_M(ISO|OSI)"]]);
  assert.equal(added.default, def, "the Default class is passed through");
  assert.deepEqual(withAssignment(added, "SPI_MISO", "power").classes.map((c) => c.nets), [["VBUS", "SPI_MISO"], ["SPI_*", "SPI_M(ISO|OSI)"]], "a pattern is added to the class chosen and stays where it was");
  assert.deepEqual(withAssignment(added, "SPI_M(ISO|OSI)", "Default").classes.map((c) => c.nets), [["VBUS"], ["SPI_*"]], "Default: the pattern comes off the other classes");
  assert.equal(withAssignment(settings, "  ", "bus"), settings, "an empty pattern assigns nothing");
  assert.deepEqual(settings.classes.map((c) => c.nets), [["VBUS"], ["SPI_*"]], "nothing is changed in place");
});

