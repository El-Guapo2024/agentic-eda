// `SCH_EDITOR_CONTROL::AssignNetclass`'s `getNetNamePattern` (eeschema/tools/sch_editor_control.cpp at 8303b2ad): what a selected connection offers the
// Assign Netclass dialog as its pattern.
import { hasAutoGeneratedNetname } from "./boardSetupRules";
import { parseBusGroup, parseBusVector } from "./busPattern";

/**
 * A bus's name as a pattern over its members (`ParseBusVector( netName, &prefix )` -> `prefix*`, `ParseBusGroup` -> `prefix.*`), a net's own name, or null
 * for a net that no label, sheet pin or power pin drives (`GetDriverPriority( driver ) < SHEET_PIN`: KiCad named it itself, `Net-(..)` / `unconnected-(..)`),
 * which stops the command with "All selected nets must be labeled to assign a netclass.".
 */
export function netNamePattern(net: string, bus: boolean): string | null {
  if (bus) {
    if (parseBusVector(net)) return `${net.slice(0, net.indexOf("["))}*`;
    if (parseBusGroup(net)) return `${net.slice(0, Math.max(0, net.indexOf("{")))}.*`;
    return net;
  }
  return hasAutoGeneratedNetname(net) ? null : net;
}
