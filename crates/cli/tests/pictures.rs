//! The pictures `eda` writes are kicad-cli's (docs/ARCHITECTURE.md, "Engines"): `eda schematic`'s `schematic.svg` is `kicad-cli sch export svg`
//! of the derived schematic, and the judge's `judge_<stage>.{svg,png}` are `kicad-cli sch|pcb export svg|png` of the derived files
//! (`eda_kicad_engine::pictures`). The hand-drawn `eda-render` sheet and the judge's `render_board_svg` are inactive, reached only with
//! `EDA_RUST_PICTURES=1`.
//!
//! Fast tier: without kicad-cli the stage still passes and says why no picture was drawn, the judge fails `judge_unavailable` naming
//! kicad-cli, and the opt-in still draws the inactive picture. Slow tier (`EDA_SLOW_TESTS=1`, the real kicad-cli): the files are KiCad's
//! plots of this design -- an SVG KiCad's plotter wrote, holding every reference of the schematic (KiCad's SVG plotter keeps each text's
//! string in a `<desc>`), and PNGs.

use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

fn eda(args: &[&str], env: &[(&str, &str)]) -> (bool, String) {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_eda"));
    cmd.args(args).env_remove("EDA_RUST_PICTURES").env("ANTHROPIC_API_KEY", "");
    for (k, v) in env {
        cmd.env(k, v);
    }
    let out = cmd.output().expect("run eda");
    (out.status.success(), format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)))
}

fn slow() -> bool {
    if std::env::var_os("EDA_SLOW_TESTS").is_none() {
        eprintln!("skipped: slow test; set EDA_SLOW_TESTS=1 to run it");
        return false;
    }
    true
}

fn scratch(tag: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("eda_pictures_{}_{tag}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn example() -> String {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../examples/ldo.yaml").display().to_string()
}

/// No kicad-cli anywhere: `EDA_KICAD_CLI` names nothing and `PATH` has no `kicad-cli` (nor `which`).
fn no_cli(dir: &Path) -> Vec<(&'static str, String)> {
    let empty = dir.join("empty-path");
    std::fs::create_dir_all(&empty).unwrap();
    vec![("EDA_KICAD_CLI", dir.join("no-kicad-cli").display().to_string()), ("PATH", empty.display().to_string())]
}

fn refs_of(design: &Path) -> Vec<String> {
    let d: Value = serde_json::from_str(&std::fs::read_to_string(design).unwrap()).unwrap();
    let mut refs: Vec<String> = d["schematic"]["symbols"].as_array().unwrap().iter().filter_map(|s| s["id"].as_str().map(str::to_string)).collect();
    refs.sort();
    refs
}

/// An SVG document KiCad's plotter wrote (`generator` its `<desc>`), whole.
fn assert_kicad_svg(path: &Path, plotter: &str) -> String {
    let svg = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    assert!(svg.trim_start().starts_with("<?xml") && svg.contains("<svg") && svg.trim_end().ends_with("</svg>"), "{} is not a whole SVG document", path.display());
    assert!(svg.contains(&format!("<desc>Image generated by {plotter}")), "{} was not plotted by KiCad's {plotter}", path.display());
    svg
}

fn assert_png(path: &Path) {
    let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    assert!(bytes.starts_with(b"\x89PNG\r\n\x1a\n") && bytes.len() > 10_000, "{} is not a PNG picture", path.display());
}

#[test]
fn without_kicad_cli_the_schematic_stage_says_why_there_is_no_picture() {
    let dir = scratch("nocli");
    let env = no_cli(&dir);
    let env: Vec<(&str, &str)> = env.iter().map(|(k, v)| (*k, v.as_str())).collect();
    let out = dir.join("out");
    let (good, log) = eda(&["schematic", &example(), "-o", out.to_str().unwrap()], &env);
    assert!(good, "a missing picture is not a failed stage:\n{log}");
    assert!(log.contains("schematic.svg not written: kicad-cli not found"), "{log}");
    assert!(!out.join("schematic.svg").exists());
    assert!(out.join("design.json").exists());

    // The judge has no fallback picture: it fails, naming kicad-cli, before it would ask the model.
    let (good, log) = eda(&["judge", &example(), "--design", out.join("design.json").to_str().unwrap(), "-o", out.to_str().unwrap()], &env);
    assert!(!good);
    assert!(log.contains("judge_unavailable") && log.contains("kicad-cli not found"), "{log}");
    assert!(!out.join("judge_schematic.svg").exists());
}

#[test]
fn the_inactive_rust_picture_is_still_reachable_by_its_opt_in() {
    let dir = scratch("rust");
    let mut env = no_cli(&dir);
    env.push(("EDA_RUST_PICTURES", "1".into()));
    let env: Vec<(&str, &str)> = env.iter().map(|(k, v)| (*k, v.as_str())).collect();
    let out = dir.join("out");
    let (good, log) = eda(&["schematic", &example(), "-o", out.to_str().unwrap()], &env);
    assert!(good, "{log}");
    let svg = std::fs::read_to_string(out.join("schematic.svg")).unwrap();
    // eda-render's own drawing: its IC box class and the references as text.
    assert!(svg.contains("class=\"box-ic\"") && svg.contains(">U1<"), "{}", &svg[..400.min(svg.len())]);
}

#[test]
fn the_schematic_and_the_judges_pictures_are_kicad_clis_plots() {
    if !slow() {
        return;
    }
    let dir = scratch("kicad");
    let out = dir.join("out");
    let (good, log) = eda(&["pipeline", &example(), "-o", out.to_str().unwrap(), "--seed", "0"], &[]);
    assert!(good, "{log}");
    let refs = refs_of(&out.join("design.json"));
    assert!(refs.len() >= 5, "{refs:?}");

    // eda schematic's picture: Eeschema's SVG plot of the derived sheet, every reference on it, the title block naming the derived file.
    let sch = assert_kicad_svg(&out.join("schematic.svg"), "Eeschema-SVG");
    for r in &refs {
        assert!(sch.contains(&format!("<desc>{r}</desc>")), "schematic.svg has no {r}");
    }
    assert!(sch.contains("<desc>File: ldo.kicad_sch</desc>"));

    // The judge (no API key: it fails at the model, after writing what it would have shown it).
    let (good, log) = eda(&["judge", &example(), "--design", out.join("design.json").to_str().unwrap(), "-o", out.to_str().unwrap()], &[]);
    assert!(!good && log.contains("ANTHROPIC_API_KEY"), "the judge got as far as the model:\n{log}");
    let judged = assert_kicad_svg(&out.join("judge_schematic.svg"), "Eeschema-SVG");
    assert_eq!(judged.lines().filter(|l| !l.contains("date")).collect::<Vec<_>>(), sch.lines().filter(|l| !l.contains("date")).collect::<Vec<_>>(), "the judge sees the sheet eda schematic drew");
    let placement = assert_kicad_svg(&out.join("judge_placement.svg"), "PCBNEW");
    let routing = assert_kicad_svg(&out.join("judge_routing.svg"), "PCBNEW");
    for r in &refs {
        assert!(placement.contains(&format!("<desc>{r}</desc>")) && routing.contains(&format!("<desc>{r}</desc>")), "the board pictures have no {r}");
    }
    // The placement is judged without the tracks: the routed picture draws more.
    assert!(routing.len() > placement.len(), "routing {} <= placement {} bytes", routing.len(), placement.len());
    for stage in ["schematic", "placement", "routing"] {
        assert_png(&out.join(format!("judge_{stage}.png")));
    }
}
