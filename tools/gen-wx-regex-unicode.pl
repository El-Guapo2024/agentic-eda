#!/usr/bin/perl
# Writes crates/model/src/wx_regex_unicode.rs: the Unicode properties PCRE2's \p{..} reads (UI-LEFT-3 C3-11), from Perl's Unicode::UCD (Unicode 15.0 with
# Perl 5.38; the box's libpcre2-32 10.42 has Unicode 14). Run: perl tools/gen-wx-regex-unicode.pl > crates/model/src/wx_regex_unicode.rs, and
# perl tools/gen-wx-regex-unicode.pl --ts > web/studio/src/kicad-port/wxRegexNames.ts (the names alone: the browser's RegExp has the properties).
use strict;
use warnings;
use Unicode::UCD qw(prop_invlist prop_values prop_value_aliases prop_aliases);

sub ranges {
    # inclusive ranges, a single code point as one number
    my @inv = @_;
    my @out;
    for (my $i = 0; $i < @inv; $i += 2) {
        my $lo = $inv[$i];
        my $hi = defined $inv[$i + 1] ? $inv[$i + 1] - 1 : 0x10FFFF;
        push @out, sprintf("(%d,%d)", $lo, $hi);
    }
    my $text = "";
    for (my $i = 0; $i < @out; $i += 16) {
        $text .= "        " . join(",", @out[$i .. ($i + 15 < $#out ? $i + 15 : $#out)]) . ",\n";
    }
    return "&[\n$text    ]";
}

my $version = Unicode::UCD::UnicodeVersion();
my $ts = @ARGV && $ARGV[0] eq "--ts";
my @binary = qw(ASCII ASCII_Hex_Digit Alphabetic Bidi_Control Bidi_Mirrored Case_Ignorable Cased Changes_When_Casefolded Changes_When_Casemapped
    Changes_When_Lowercased Changes_When_Titlecased Changes_When_Uppercased Dash Default_Ignorable_Code_Point Deprecated Diacritic Emoji Emoji_Component
    Emoji_Modifier Emoji_Modifier_Base Emoji_Presentation Extended_Pictographic Extender Grapheme_Base Grapheme_Extend Grapheme_Link Hex_Digit
    IDS_Binary_Operator IDS_Trinary_Operator ID_Continue ID_Start Ideographic Join_Control Logical_Order_Exception Lowercase Math
    Noncharacter_Code_Point Pattern_Syntax Pattern_White_Space Prepended_Concatenation_Mark Quotation_Mark Radical Regional_Indicator
    Sentence_Terminal Soft_Dotted Terminal_Punctuation Unified_Ideograph Uppercase Variation_Selector White_Space XID_Continue XID_Start);
sub binary_names {
    my ($b) = @_;
    my @a = prop_aliases($b);
    @a = ("Gr_Link", "Grapheme_Link") if !@a && $b eq "Grapheme_Link";    # deprecated: Perl names it no more
    my ($short, $long) = ($a[0], $a[1] // $a[0]);
    ($short, $long) = ($long, $short) if length($short) > length($long);
    return ($long, $short);
}
sub script_names {
    my ($s) = @_;
    my @names = prop_value_aliases("sc", $s);
    return () if @names < 2;    # Katakana_Or_Hiragana: no code point has it
    my ($short, $long) = ($names[0], $names[1] // $names[0]);
    ($short, $long) = ($long, $short) if length($short) > length($long);
    return ($long, $short);
}
if ($ts) {
    print "// Generated by tools/gen-wx-regex-unicode.pl --ts from Perl's Unicode::UCD (Unicode $version): the script and binary property names PCRE2's\n";
    print "// \\p{..} reads (UI-LEFT-3 C3-11), long and short, which kicad-port/wxRegex.ts hands to the browser's RegExp. Do not edit.\n\n";
    print "export const SCRIPT_NAMES: readonly (readonly [string, string])[] = [\n";
    for my $s (sort { $a cmp $b } prop_values("sc")) {
        my ($long, $short) = script_names($s);
        print "  [\"$long\", \"$short\"],\n" if defined $long;
    }
    print "];\n\nexport const BINARY_NAMES: readonly (readonly [string, string])[] = [\n";
    for my $b (@binary) {
        my ($long, $short) = binary_names($b);
        print "  [\"$long\", \"$short\"],\n";
    }
    print "];\n";
    exit 0;
}
print "//! Generated by tools/gen-wx-regex-unicode.pl from Perl's Unicode::UCD (Unicode $version): the properties PCRE2's `\\p{..}` reads (UI-LEFT-3\n";
print "//! C3-11) -- the general categories, the scripts (`sc:` and, for a bare name, the script extensions PCRE2 10.40 and later match), the binary\n";
print "//! properties -- as inclusive ranges of code points. Do not edit.\n\n";
# the general categories, by their two-letter names (Cn: whatever is in none)
my @gc = qw(Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co);
print "pub(crate) const GENERAL_CATEGORIES: &[(&str, &[(u32, u32)])] = &[\n";
for my $g (@gc) {
    print "    (\"$g\", " . ranges(prop_invlist("gc=$g")) . "),\n";
}
print "];\n\n";
print "pub(crate) const SCRIPTS: &[(&str, &str, &[(u32, u32)], Option<&[(u32, u32)]>)] = &[\n";
for my $s (sort { $a cmp $b } prop_values("sc")) {
    my ($long, $short) = script_names($s);
    next unless defined $long;
    my ($sc, $scx) = (ranges(prop_invlist("sc=$s")), ranges(prop_invlist("scx=$s")));
    # the script extensions, where they are not the script's own code points
    print "    (\"$long\", \"$short\", $sc, " . ($scx eq $sc ? "None" : "Some($scx)") . "),\n";
}
print "];\n\n";
print "pub(crate) const BINARY: &[(&str, &str, &[(u32, u32)])] = &[\n";
for my $b (@binary) {
    my ($long, $short) = binary_names($b);
    print "    (\"$long\", \"$short\", " . ranges(prop_invlist($b)) . "),\n";
}
print "];\n";
